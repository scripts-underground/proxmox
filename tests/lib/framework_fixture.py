"""Framework definitions for cold app fixtures; only external effects are modeled.

Do not manufacture a subset of install.func's API or detected state. The bundle
owner defers source-time bootstrap, then calls _bootstrap/detect_os itself.
"""
from pathlib import Path
import re
import sys


def install_fixture(root, explicit_platform=False):
    text = (Path(root) / 'misc/install.func').read_text()
    if explicit_platform:
        # Service-helper matrices deliberately select an init/family different
        # from the surrounding VM. Keep the real detector and complete API,
        # then apply only the explicit fixture inputs after real detection.
        keys = ('OS_TYPE', 'OS_FAMILY', 'OS_VERSION', 'PKG_MANAGER', 'INIT_SYSTEM')
        assert text.count('detect_os() {') == 1
        text = ''.join('_fixture_' + key + '=${' + key + '-}\n' for key in keys) + text.replace('detect_os() {', '_fixture_detect_os() {', 1)
        text += '\ndetect_os() {\n  _fixture_detect_os\n'
        text += ''.join('  [[ -z "$_fixture_' + key + '" ]] || ' + key + '="$_fixture_' + key + '"\n' for key in keys)
        text += '}\n'
    return text + r'''
# These effects belong to the fixture, not a second framework implementation.
_bootstrap() { :; }
pkg_install() { :; }
setup_lxc() { :; }
'''


def minimal_install_models(root):
    """Find ad-hoc install APIs, excluding intentional boundary-only probes.

    These exceptions execute synthetic hooks or inspect generated bytes without
    executing an app. They do not promise an app framework environment.
    """
    exceptions = {
        'gpu-passthrough.test.sh', 'container-install-failure.test.sh',
        'maintenance-temp-root.test.sh', 'maintenance-build-temp.test.sh',
        'maintenance-receiving-context.test.sh', 'maintenance-addon-writer.test.sh',
        'lib/terminal_display_fixture.py',
        'lib/batch_metadata_fixture.py', 'lib/framework_fixture.py',
        'runtime-hooks/harness-controls.sh',
    }
    found = []
    for path in sorted((Path(root) / 'tests').rglob('*')):
        if path.suffix not in ('.sh', '.py', '.func'):
            continue
        text = path.read_text()
        if 'install.func' in text and re.search(r'(?:setup_lxc|pkg_install|detect_os)\(\)\s*\{', text):
            name = path.relative_to(Path(root) / 'tests').as_posix()
            if name not in exceptions:
                found.append(name)
    return found


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[2] == '--audit':
        unexpected = minimal_install_models(sys.argv[1])
        if unexpected:
            sys.exit('Ad-hoc app framework models: ' + ', '.join(unexpected))
    else:
        assert len(sys.argv) == 2 or sys.argv[2:] == ['--explicit-platform']
        print(install_fixture(sys.argv[1], explicit_platform=len(sys.argv) == 3), end='')
